using ComputePipeline: NestedSearchTree, Computed, compute_identity, add_key!

"""
    Inherit([callback = identity], keys, [fallback = NoFallback()])

Marks an attribute definition as inheriting from a parent theme. Objects of this
type are generated by `@inherit [callback] keys [fallback]` within `@recipe`,
`@Block` and `@DocumentedAttributes`.

Arguments:
- `callback` is an optional callback that applies to the inherited value before
    it is used as an attribute
- `keys` is a tuple of keys referring to a potentially nested attribute in the
    `theme(scene)` or the global `theme(nothing)`
- `fallback` is an optional value used if the value can't be inherited. If it is
    not provided it defaults to `NoFallback()` which requires the value to be
    inherited. `fallback` can also be another `Inherit`.
"""
struct Inherit{N}
    callback::Any
    keys::NTuple{N, Symbol}
    fallback::Any
end
struct NoFallback end

Inherit(keys::Tuple{Vararg{Symbol}}) = Inherit(identity, keys, NoFallback())
Inherit(keys::Tuple{Vararg{Symbol}}, fallback) = Inherit(identity, keys, fallback)
Inherit(f, keys::Tuple{Vararg{Symbol}}) = Inherit(f, keys, NoFallback())

# For replacing `@inherit x` with `@inherit :x`
default_key_expr(x::Symbol) = :(($(QuoteNode(x)),))
default_key_expr(x::QuoteNode) = :(($x,))
function default_key_expr(expr::Expr)
    if !(expr.head == :tuple && all(x -> x isa QuoteNode, expr.args))
        error("$expr is not a valid inheritance key")
    end
    for i in eachindex(expr.args)
        expr.args[i] = ifelse(expr.args[i] isa Symbol, QuoteNode(expr.args[i]), expr.args[i])
    end
    return expr
end

# Parses specifically `@inherit ...`  and its compat forms
function get_default_expr(expr, attribute_path, full_expr, local_vars)
    # This is split off to allow Inherit(key, Inherit(...)) in some capacity
    if MacroTools.@capture(expr, inherit(scene_, key_, fallback_))
        # This was only supported with fallback by Blocks
        fb = get_default_expr(fallback, attribute_path, full_expr, local_vars)
        return :(Makie.Inherit($(default_key_expr(key)), $fb))
    elseif MacroTools.@capture(expr, map(f_, inherit(scene_, key_, fallback_)))
        # This was only supported with fallback by Blocks
        fb = get_default_expr(fallback, attribute_path, full_expr, local_vars)
        return :(Makie.Inherit($f, $(default_key_expr(key)), $fb))
    elseif MacroTools.@capture(expr, theme(scene_, key_))
        return :(Makie.Inherit($(default_key_expr(key))))

    elseif MacroTools.@capture(expr, @inherit callback_ key_ fallback_)
        fb = get_default_expr(fallback, attribute_path, full_expr, local_vars)
        return :(Makie.Inherit($callback, $(default_key_expr(key)), $fb))
    elseif MacroTools.@capture(expr, @inherit key_ fallback_)
        # TODO: How do we figure out if this is @inherit callback key instead?
        fb = get_default_expr(fallback, attribute_path, full_expr, local_vars)
        return :(Makie.Inherit($(default_key_expr(key)), $fb))
    elseif MacroTools.@capture(expr, @inherit key_)
        return :(Makie.Inherit($(default_key_expr(key))))

    elseif MacroTools.@capture(expr, @attributes attrblock_)
        path = join(attribute_path, " -> ")
        error("`@attributes` cannot be used with an @inherit (or similar) block. Used in $path = $full_expr.")
    elseif MacroTools.@capture(expr, Makie.defaultfont())
        path = join(attribute_path, " -> ")
        @warn """
        Using `Makie.defaultfont()` as an attribute default in `@recipe` or `@Block` causes segfaults due to invalid font pointers from caching.
        Replacing it with `\"default\"` in `$path = $full_expr`"
        """
        return :("default")
    else
        return MacroTools.postwalk(expr) do x
            if x isa Symbol && !in(x, local_vars)
                return esc(x)
            end
            return x
        end
    end
end

function default_expr_string(default)
    is_macrocall = default isa Expr && default.head === :macrocall
    if is_macrocall && default.args[1] === Symbol("@attributes")
        # for normal recipes
        return "Attributes(...)"
    elseif MacroTools.@capture(default, Attributes(args__))
        # for old recipes
        return "Attributes(...)"
    elseif MacroTools.@capture(default, Makie.DocumentedAttributes(args__))
        # for old recipes, maybe also better to have in general?
        return "Attributes(...)"
    else
        return string(MacroTools.prewalk(MacroTools.rmlines, default))
    end
end

default_expr_string(x::String) = repr(x)

