function has_nested_key(attr::DocumentedAttributes, keys::Symbol...)
    idx = 1
    for key in keys
        if idx < 0 || !haskey(attr.nesting.keytables[idx], key)
            return false
        end
        idx = attr.nesting.keytables[idx]
    end
    return true
end

